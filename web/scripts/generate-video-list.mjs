#!/usr/bin/env node
/**
 * Scan public/videos/*.mp4 and write src/generated/videoList.ts.
 *
 * Runs automatically before `npm run dev` and `npm run build` (npm
 * predev/prebuild hooks). The output file is gitignored — the source of
 * truth is whatever .mp4 files actually live in public/videos/ at build
 * time. Add a video → run dev/build → it appears in the background pool.
 */
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const webRoot = join(here, '..')
const videosDir = join(webRoot, 'public', 'videos')
const outFile = join(webRoot, 'src', 'generated', 'videoList.ts')

let files = []
try {
  files = readdirSync(videosDir)
    .filter((f) => f.toLowerCase().endsWith('.mp4'))
    .sort()
} catch (e) {
  console.warn(`[generate-video-list] cannot read ${videosDir}: ${e.message}`)
}

const paths = files.map((f) => `/videos/${f}`)

const content = `// AUTO-GENERATED by scripts/generate-video-list.mjs.
// Do not edit by hand — run \`npm run dev\` or \`npm run build\` to refresh.
export const VIDEOS: readonly string[] = ${JSON.stringify(paths, null, 2)}
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, content)
console.log(`[generate-video-list] wrote ${paths.length} entries → ${outFile}`)
